(function () {
  "use strict";

  var STORAGE_KEY = "pouyab-lang";

  function getLangMeta(code) {
    for (var i = 0; i < POUYAB_LANGS.length; i++) {
      if (POUYAB_LANGS[i].code === code) return POUYAB_LANGS[i];
    }
    return POUYAB_LANGS[0];
  }

  function currentLang() {
    var saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    if (saved && POUYAB_I18N[saved]) return saved;
    return "fa";
  }

  function t(key) {
    var lang = currentLang();
    var dict = POUYAB_I18N[lang] || {};
    if (dict[key] !== undefined) return dict[key];
    if (POUYAB_I18N.fa[key] !== undefined) return POUYAB_I18N.fa[key];
    return key;
  }

  function setLang(code, persist) {
    if (!POUYAB_I18N[code]) return;
    var meta = getLangMeta(code);
    var html = document.documentElement;
    html.setAttribute("lang", code);
    html.setAttribute("dir", meta.dir);
    try { if (persist !== false) localStorage.setItem(STORAGE_KEY, code); } catch (e) {}

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });

    if (window.POUYAB_AFTER_LANG) window.POUYAB_AFTER_LANG(code);

    var switcher = document.getElementById("pouyabLangSwitcher");
    if (switcher) {
      var btns = switcher.querySelectorAll("[data-lang]");
      btns.forEach(function (b) {
        b.classList.toggle("is-active", b.getAttribute("data-lang") === code);
      });
    }
    var currentLabel = document.querySelector(".pouyab-lang-label");
    if (currentLabel) currentLabel.textContent = meta.label;
  }

  function initSwitcher() {
    var switcher = document.getElementById("pouyabLangSwitcher");
    if (!switcher) return;
    var currentLabel = switcher.querySelector(".pouyab-lang-label") ;
    if (currentLabel) currentLabel.textContent = getLangMeta(currentLang()).label;

    switcher.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.addEventListener("click", function () {
        setLang(btn.getAttribute("data-lang"));
        btn.classList.add("is-active");
      });
    });
  }

  document.addEventListener("DOMContentLoaded", function () {
    setLang(currentLang(), false);
    initSwitcher();
  });
  if (document.readyState !== "loading") {
    setLang(currentLang(), false);
    initSwitcher();
  }
})();